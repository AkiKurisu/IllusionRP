using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Illusion.ShaderTools;
using Illusion.ShaderTools.Syntax.HLSL;

namespace Illusion.Rendering.Editor
{
    internal static class PathTracingInlineBindingCarrier
    {
        internal const string Version = "binding-carrier-1";
        private const string Extension = "_PathTracingInlineExtension";

        public static string Generate(string source, DxcCompiler.Reflection reflection)
        {
            var document = ShaderSource.ParseHlsl(source);
            var edits = new List<(int Start, int Length, string Text)>();
            foreach (var declaration in document.Declarations)
                if (declaration.Node is StructDefinitionNode structure) RemoveMethods(structure.StructType);
            source = ShaderSource.Edit(source, edits);
            var roots = new HashSet<HlslDeclaration>();
            var names = new Dictionary<string, string>();
            var resources = reflection.Resources.Where(r => r.Type != 0).ToDictionary(r => r.Name);
            var globals = reflection.ConstantBuffers.SelectMany(c => c.Variables).Select(v => v.Name).ToHashSet();
            foreach (string name in resources.Keys.Concat(globals))
            {
                var found = document.Find(name).ToArray();
                if (found.Length == 0) found = document.Declarations.Where(d => d.Names.Contains(name)).ToArray();
                if (found.Length != 1) throw new InvalidOperationException($"Binding declaration '{name}' is not unique.");
                roots.Add(found[0]);
                names[name] = found[0].Scope.Length == 0 ? name : found[0].Scope + "::" + name;
            }
            var required = document.Reachable(roots);
            var code = new StringBuilder("// Generated by IllusionRP. Do not edit.\n#pragma only_renderers d3d11\n#pragma use_dxc\n#pragma require inlineraytracing\n#pragma kernel InlineMain\n");
            foreach (var declaration in document.Declarations.Where(required.Contains))
            {
                var scopes = declaration.Scope.Split(new[] { "::" }, StringSplitOptions.RemoveEmptyEntries);
                foreach (var scope in scopes) code.Append("namespace ").Append(scope).Append(" {\n");
                if (declaration.Node is FunctionNode)
                    throw new InvalidOperationException($"Binding declaration depends on function '{declaration.Key}'.");
                if (declaration.Node is VariableDeclarationStatementNode variable && roots.Contains(declaration))
                {
                    string modifiers = source.Substring(variable.Span.StartIndex, variable.Kind.Span.StartIndex - variable.Span.StartIndex);
                    foreach (var field in variable.Declarators)
                    {
                        if (resources.TryGetValue(field.Name.Identifier, out var resource))
                        {
                            char register = resource.Type == 3 ? 's' : IsUav(resource.Type) ? 'u' : 't';
                            code.Append(modifiers).Append(ShaderSource.Code(source, variable.Kind)).Append(' ').Append(resource.Name);
                            foreach (var rank in field.ArrayRanks) code.Append(ShaderSource.Code(source, rank));
                            code.Append($" : register({register}{resource.BindPoint}, space{resource.Space});\n");
                        }
                        else if (globals.Contains(field.Name.Identifier))
                        {
                            code.Append(modifiers).Append(ShaderSource.Code(source, variable.Kind)).Append(' ').Append(ShaderSource.Code(source, field)).Append(";\n");
                        }
                    }
                }
                else
                    code.Append(ShaderSource.Code(source, declaration.Node)).Append('\n');
                foreach (var scope in scopes) code.Append("}\n");
            }
            code.Append("[numthreads(8,4,1)]\nvoid InlineMain(uint2 pixel : SV_DispatchThreadID)\n{\nif (_ScreenParams.x >= 0) return;\nuint sum = pixel.x;\n");
            foreach (var buffer in reflection.ConstantBuffers)
                foreach (var field in buffer.Variables)
                    code.Append("sum += (uint)(").Append(Scalar(names[field.Name], field.Type)).Append(");\n");
            int index = 0;
            string sampleTexture = names[reflection.Resources.First(r => r.Type == 2 && r.Dimension == 4 && r.ReturnType == 5).Name];
            foreach (var resource in resources.Values)
            {
                if (resource.Name == Extension) continue;
                string name = names[resource.Name] + (resource.BindCount > 1 ? "[NonUniformResourceIndex(pixel.x)]" : "");
                string n = "d" + index++;
                if (resource.Type == 3)
                    code.Append($"sum += (uint){sampleTexture}.SampleLevel({name}, 0, 0).x;\n");
                else if (resource.Type == 12)
                    code.Append($"RayQuery<0> q; RayDesc ray = (RayDesc)0; q.TraceRayInline({name}, 0, 0, ray); sum += q.Proceed();\n");
                else
                {
                    int dimensions = resource.Dimension switch
                    {
                        1 => resource.Type == 5 || resource.Type == 6 || resource.Type == 11 ? 2 : 1,
                        2 => 1,
                        3 or 4 or 9 => 2,
                        5 or 8 or 10 => 3,
                        _ => throw new InvalidOperationException($"Unsupported binding probe: {resource.Name} ({resource.Dimension}).")
                    };
                    code.Append("uint ").Append(string.Join(", ", Enumerable.Range(0, dimensions).Select(i => n + i))).Append(";\n");
                    code.Append(name).Append(".GetDimensions(").Append(string.Join(", ", Enumerable.Range(0, dimensions).Select(i => n + i))).Append(");\n");
                    code.Append("sum += ").Append(string.Join(" + ", Enumerable.Range(0, dimensions).Select(i => n + i))).Append(";\n");
                }
            }
            code.Append(Extension).Append("[0] = uint4(sum, 0, 0, 0);\n}\n");
            return code.ToString();

            void RemoveMethods(StructTypeNode type)
            {
                foreach (var method in type.Methods)
                    edits.Add((method.Span.StartIndex, method.Span.Length, new string(' ', method.Span.Length)));
                type.Methods.Clear();
                foreach (var nested in type.NestedTypes) RemoveMethods(nested.StructType);
            }
        }

        private static string Scalar(string expression, DxcCompiler.ReflectedType type)
        {
            if (type.Description.Elements > 0) expression += "[0]";
            if (type.Members.Count > 0) return Scalar(expression + "." + type.Members[0].Name, type.Members[0].Type);
            if (type.Description.Class == 1) expression += ".x";
            else if (type.Description.Class == 2 || type.Description.Class == 3) expression += "[0][0]";
            return expression;
        }

        private static bool IsUav(uint type) => type == 4 || type == 6 || type == 8 || type == 9 || type == 10 || type == 11;

        public static void Validate(DxcCompiler.Reflection expected, DxcCompiler.Reflection actual)
        {
            foreach (var resource in expected.Resources)
            {
                bool extension = resource.Name == "g_NvidiaExt";
                string name = extension ? Extension : resource.Name;
                var matches = actual.Resources.Where(r => r.Name == name).ToArray();
                if (matches.Length != 1) throw new InvalidOperationException($"Carrier binding '{name}' is missing.");
                var found = matches[0];
                if (found.BindPoint != resource.BindPoint || found.Space != resource.Space || found.BindCount != resource.BindCount ||
                    found.Type != (extension ? 6 : resource.Type) || found.Dimension != resource.Dimension || found.ReturnType != resource.ReturnType)
                    throw new InvalidOperationException($"Carrier binding '{name}' does not match native DXIL.");
            }
            foreach (var buffer in expected.ConstantBuffers)
            {
                var found = actual.ConstantBuffers.Single(c => c.Name == buffer.Name);
                if (buffer.Size != found.Size) throw new InvalidOperationException($"Carrier cbuffer '{buffer.Name}' size differs.");
                foreach (var field in buffer.Variables)
                {
                    var value = found.Variables.Single(v => v.Name == field.Name);
                    if (value.Offset != field.Offset || value.Size != field.Size || TypeKey(value.Type) != TypeKey(field.Type))
                        throw new InvalidOperationException($"Carrier constant '{buffer.Name}.{field.Name}' layout differs.");
                }
            }
        }

        private static string TypeKey(DxcCompiler.ReflectedType type) =>
            $"{type.Description.Class}/{type.Description.Type}/{type.Description.Rows}/{type.Description.Columns}/{type.Description.Elements}/{type.Description.Offset}" +
            string.Concat(type.Members.Select(m => "|" + m.Name + ":" + TypeKey(m.Type)));
    }
}
